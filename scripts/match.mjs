import { chromium } from 'playwright'
const b = await chromium.launch(); const p = await b.newPage({viewport:{width:1440,height:900}})
const errs=[]; p.on('pageerror',e=>errs.push(e.message))
await p.goto('http://127.0.0.1:3000/#/match/m1',{waitUntil:'networkidle'}); await p.waitForTimeout(800)
console.log('breadcrumb:', (await p.locator('.breadcrumb').innerText()).replace(/\n+/g,' › '))
console.log('team codes:', await p.locator('.team-code').allInnerTexts())
console.log('market search placeholder:', await p.locator('input[aria-label="Search markets or players"]').getAttribute('placeholder'))
console.log('groups before search:', await p.locator('.market-group').count())
console.log('sels before search:', await p.locator('.sel').count())
await p.locator('input[aria-label="Search markets or players"]').fill('corner')
await p.waitForTimeout(500)
console.log('after "corner" -> groups:', await p.locator('.market-group').count(), '| sels:', await p.locator('.sel').count())
await p.locator('input[aria-label="Search markets or players"]').fill('Vardal')
await p.waitForTimeout(500)
console.log('after "Vardal" -> groups:', await p.locator('.market-group').count(), '| sels:', await p.locator('.sel').count())
await p.locator('input[aria-label="Search markets or players"]').fill('zzz')
await p.waitForTimeout(400)
console.log('after "zzz" -> empty state:', (await p.locator('.panel').first().innerText().catch(()=>'none')).replace(/\n+/g,' | '))
await p.locator('input[aria-label="Search markets or players"]').fill('')
await p.waitForTimeout(300)
console.log('cleared -> sels:', await p.locator('.sel').count())
console.log('errors:', errs.length?errs.join(' | '):'none')
await b.close()
