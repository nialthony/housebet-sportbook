import { chromium } from 'playwright'
const b = await chromium.launch(); const p = await b.newPage({viewport:{width:1440,height:900}})
const errs=[]; p.on('pageerror',e=>errs.push(e.message))
await p.goto('http://127.0.0.1:3000/#/', {waitUntil:'networkidle'}); await p.waitForTimeout(600)
await p.keyboard.press('/'); await p.waitForTimeout(200)
console.log('focused after "/":', await p.evaluate(()=>document.activeElement?.id || document.activeElement?.tagName))
await p.keyboard.type('arse'); await p.waitForTimeout(400)
console.log('search results visible:', await p.locator('text=Arsenal v Brighton').first().isVisible().catch(()=>false))
await p.keyboard.press('Escape'); await p.waitForTimeout(200)
await p.evaluate(()=>document.activeElement?.blur())
await p.keyboard.press('b'); await p.waitForTimeout(600)
console.log('hash after "b":', await p.evaluate(()=>location.hash))
console.log('bets page h1:', await p.locator('h1').first().innerText().catch(()=>'none'))
console.log('errors:', errs.length? errs.join('; ') : 'none')
await b.close()
